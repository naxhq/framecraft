/**
 * Ship the six committed preset Overpass responses beside the exported site.
 *
 *   node scripts/bundle-preset-assets.mjs            # writes out/presets/
 *   node scripts/bundle-preset-assets.mjs --out out --fixtures ../../fixtures
 *
 * WHY. On the deployed site the live Overpass round trip dominates everything
 * else by an order of magnitude: 8.5 to 32.4 s on the runs that completed,
 * `overpass-api.de` answering 504 after ~10 s on three of eight attempts, and
 * two of five measured flows that never produced a preview inside 180 s
 * (`docs/handoff/v3-00-baseline.md` 1.6 and 1.7). Every one of those requests
 * asks the same six questions, and their answers are already committed to this
 * repo as the fixtures the reference pipeline is judged on. Within static
 * hosting the build IS the shared cache, so the build can carry them.
 *
 * The file name is the sha1 of the Overpass QUERY TEXT, which is what
 * `lib/engine/osm/overpass.ts` already uses as its cache key and what
 * `python -m app.cli refresh-fixtures` already used to name the fixture. An
 * asset therefore answers exactly one query and cannot answer any other: nudge
 * the pin, change the radius or rotate the crop and the sha1 changes and the
 * mirrors are asked, as before.
 *
 * WHY IT IS NOT PART OF `npm run build`. Two reasons, both deliberate.
 * The assets are 8.7 MB, which no local build, `next dev` run or desktop
 * bundle needs. And the e2e suite route-mocks `**\/api/interpreter` and then
 * clicks the Chicago preset, several specs deliberately serving a small
 * synthetic response for speed; a bundled asset in the tree under test would
 * answer before the mock could, and those specs would silently start building
 * the real 992-building Chicago. Keeping this a separate, explicit step keeps
 * the tree the gate runs against identical to the tree it has always been.
 *
 * Run it AFTER `next build`, over the exported tree.
 */

import { gzipSync } from "node:zlib";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const webRoot = resolve(here, "..");
const repoRoot = resolve(webRoot, "..", "..");

const args = process.argv.slice(2);
function argValue(name, fallback) {
  const index = args.indexOf(name);
  return index >= 0 && index + 1 < args.length ? args[index + 1] : fallback;
}

const outDir = resolve(webRoot, argValue("--out", "out"));
const fixturesDir = resolve(repoRoot, argValue("--fixtures", "fixtures"));
const targetDir = join(outDir, "presets");

const SHA1_RE = /^[0-9a-f]{40}$/;

const index = JSON.parse(await readFile(join(fixturesDir, "presets-index.json"), "utf-8"));
if (!Array.isArray(index.presets) || index.presets.length === 0) {
  throw new Error(`${fixturesDir}/presets-index.json lists no presets`);
}

await mkdir(targetDir, { recursive: true });

const manifest = {
  note:
    "Overpass responses for the built-in presets, gzipped. Keyed by the sha1 of the Overpass query text, which is lib/engine/osm/overpass.ts's cache key. Generated by apps/web/scripts/bundle-preset-assets.mjs.",
  attribution: index.attribution ?? "© OpenStreetMap contributors",
  endpoint: index.endpoint ?? null,
  generated_at: new Date().toISOString(),
  queries: {},
};

let rawTotal = 0;
let gzipTotal = 0;

for (const preset of index.presets) {
  const file = preset.fixture_file;
  const sha1 = String(file).replace(/\.json$/, "");
  if (!SHA1_RE.test(sha1)) {
    throw new Error(`preset ${preset.preset_id}: fixture_file "${file}" is not <40 hex>.json, so it is not a query sha1`);
  }

  const raw = await readFile(join(fixturesDir, file));
  // Parse before shipping: an asset that cannot be read back is worse than no
  // asset, because the client would spend the download before falling back.
  const parsed = JSON.parse(raw.toString("utf-8"));
  if (!Array.isArray(parsed.elements)) {
    throw new Error(`preset ${preset.preset_id}: ${file} has no elements array`);
  }
  if (typeof preset.element_count === "number" && parsed.elements.length !== preset.element_count) {
    throw new Error(
      `preset ${preset.preset_id}: ${file} has ${parsed.elements.length} elements, the index says ${preset.element_count}`,
    );
  }

  const gz = gzipSync(raw, { level: 9 });
  await writeFile(join(targetDir, `${sha1}.json.gz`), gz);

  manifest.queries[sha1] = {
    preset_id: preset.preset_id,
    bytes: raw.length,
    gzip_bytes: gz.length,
    element_count: parsed.elements.length,
  };
  rawTotal += raw.length;
  gzipTotal += gz.length;
  console.log(
    `${preset.preset_id.padEnd(20)} ${String(raw.length).padStart(9)} B -> ${String(gz.length).padStart(8)} B gzip  ${sha1}.json.gz`,
  );
}

await writeFile(join(targetDir, "index.json"), `${JSON.stringify(manifest, null, 2)}\n`);

const count = Object.keys(manifest.queries).length;
console.log(
  `bundle-preset-assets: ${count} preset response(s) written to ${targetDir}, ${rawTotal} B raw -> ${gzipTotal} B gzip`,
);

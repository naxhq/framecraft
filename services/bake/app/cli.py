"""FrameCraft bake-service CLI.

Usage::

    uv run python -m app.cli refresh-fixtures [--preset ID ...] [--if-missing]
    uv run python -m app.cli scene --preset chicago-loop [--out FILE]
    uv run python -m app.cli scene --lat 41.88 --lon -87.62 --radius 900 [--rotation 0]

Structure: every subcommand is registered by its own ``_add_<name>`` function
that attaches a ``handler`` default, and ``main`` just dispatches.  Later phases
add ``bake`` (mesh-bake) and ``validate`` (qa-gate) by writing one more
``_add_*`` function and one line in :func:`build_parser` - nothing else here
needs to change.
"""

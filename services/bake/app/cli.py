"""FrameCraft bake-service CLI.

Usage::

    uv run python -m app.cli refresh-fixtures [--preset ID ...] [--if-missing]
    uv run python -m app.cli scene --preset chicago-loop [--out FILE]
    uv run python -m app.cli scene --lat 41.88 --lon -87.62 --radius 900 [--rotation 0]

Structure: every subcommand is registered by its own ``_add_<name>`` function
that attaches a ``handler`` default, and ``main`` just dispatches.  Later phases
add ``bake`` (mesh-bake) and ``validate`` (qa-gate) by writing one more
``_add_*`` function and one line in :func:`build_parser` - nothing else here
needs to change.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Sequence

from app.contracts import SceneRequest
from app.ingest import normalize, overpass, presets

FIXTURES_DIR = overpass.FIXTURES_DIR
PRESETS_INDEX = FIXTURES_DIR / "presets-index.json"
_SHA1_FIXTURE_RE = re.compile(r"^[0-9a-f]{40}\.json$")

#: Courtesy pause between preset fetches, per the Overpass usage policy.
REFRESH_PAUSE_S = 5.0



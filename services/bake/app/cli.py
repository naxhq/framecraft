def _compact_pydantic_error(exc: Exception) -> str:
    """One line naming the offending fields, instead of pydantic's block.

    ``ValidationError`` is a fine thing to raise inside the service; printed at
    a CLI it is a traceback, and a traceback is not a validation verdict.
    """
    errors = getattr(exc, "errors", None)
    if not callable(errors):
        return str(exc)
    parts: list[str] = []
    for err in errors():
        loc = ".".join(str(p) for p in err.get("loc", ())) or "(root)"
        parts.append(f"{loc}: {err.get('msg', 'invalid')}")
    if not parts:
        return str(exc)
    return "; ".join(parts[:3]) + (f"; +{len(parts) - 3} more" if len(parts) > 3 else "")


def _ellipsis(text: str, width: int) -> str:
    """Trim a message to the report table's column without hiding the point."""
    return text if len(text) <= width else text[: width - 3] + "..."


def _cli_overrides(plate_mm: float | None, nozzle_mm: float | None) -> dict[str, Any]:
    overrides: dict[str, Any] = {}
    if plate_mm is not None:
        overrides["plate_mm"] = plate_mm
    if nozzle_mm is not None:
        overrides["nozzle_mm"] = nozzle_mm
    return overrides


def _params_from_sidecar(
    path: Path, plate_mm: float | None, nozzle_mm: float | None
) -> tuple["PrintParams", str, str | None]:
    """PrintParams for a file, plus where they came from and what went wrong.

    Order of precedence: the file's ``<stem>.json`` bake sidecar, then the
    ``--plate-mm`` / ``--nozzle-mm`` overrides on top of it, then the contract
    defaults for everything unset.

    A sidecar that EXISTS but cannot be used - unreadable, not JSON, carrying no
    ``print_params`` object, or carrying values the FROZEN contract rejects - is
    neither fatal nor silently ignored.  It comes back as the third element so
    ``cmd_validate`` can print a ``sidecar_params`` FAIL row and still judge the
    mesh against whatever the caller named on the command line; before this the
    contract's own bounds check reached the terminal as a pydantic traceback,
    and a file with a mis-recorded plate size could not be validated at all.
    """
    from app.contracts import PrintParams

    overrides = _cli_overrides(plate_mm, nozzle_mm)
    sidecar = path.with_suffix(".json")
    fallback_source = "command line" if overrides else "defaults"

    def _fallback(reason: str) -> tuple[PrintParams, str, str]:
        # The sidecar contributes nothing; the caller's overrides still do.
        return PrintParams(**overrides), fallback_source, reason

    if not sidecar.is_file():
        return PrintParams(**overrides), fallback_source, None

    try:
        payload = json.loads(sidecar.read_text(encoding="utf-8"))
    except OSError as exc:
        return _fallback(f"cannot read {sidecar.name} ({exc.strerror or exc})")
    except ValueError as exc:
        return _fallback(f"{sidecar.name} is not valid JSON ({exc})")
    if not isinstance(payload, dict) or not isinstance(payload.get("print_params"), dict):
        return _fallback(f"{sidecar.name} carries no print_params object")

    data = dict(payload["print_params"])
    data.update(overrides)
    try:
        params = PrintParams(**data)
    except Exception as exc:  # pydantic.ValidationError, and anything like it
        return _fallback(_compact_pydantic_error(exc))
    source = f"sidecar {sidecar.name}" + (" + command line" if overrides else "")
    return params, source, None


def _index_stl_triangle_soup(mesh: "trimesh.Trimesh") -> tuple["trimesh.Trimesh", int]:
    """Weld the *exactly* coincident vertices of an STL triangle soup.

    A binary STL stores three free-floating vertices per facet and has no index,
    so ``trimesh.load(..., process=False)`` hands back 3F vertices for F faces
    and every edge is "shared by one face": manifold, watertight and
    self_intersection all fail on a file the 3MF of the same model passes.  The
    weld here is bitwise (``np.unique`` on the float32 rows the file itself
    stores), never a tolerance pass: it re-indexes the soup and cannot close a
    real crack, so the topology this command exists to judge is unchanged.
    """
    import numpy as np
    import trimesh

    vertices, inverse = np.unique(np.asarray(mesh.vertices), axis=0, return_inverse=True)
    removed = len(mesh.vertices) - len(vertices)
    if removed <= 0:
        return mesh, 0
    faces = np.asarray(inverse).reshape(-1)[np.asarray(mesh.faces)]
    welded = trimesh.Trimesh(vertices=vertices, faces=faces, process=False, validate=False)
    return welded, removed



def _write_presets_index(entries: list[dict[str, Any]]) -> None:
    payload = {
        "note": (
            "Generated by `python -m app.cli refresh-fixtures`. Maps each preset to its "
            "raw Overpass fixture, which is named after the sha1 of the query text (03)."
        ),
        "attribution": "© OpenStreetMap contributors",
        "endpoint": overpass.PRIMARY_ENDPOINT,
        "presets": entries,
    }
    PRESETS_INDEX.write_text(
        json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )


def _index_entry(
    preset: presets.Preset,
    raw: dict[str, Any],
    path: Path,
    fetched_at: str | None = None,
) -> dict[str, Any]:
    """One presets-index.json row. ``fetched_at`` is carried over for a fixture
    that was skipped rather than re-fetched, so the timestamp never lies."""
    return {
        "preset_id": preset.id,
        "label": preset.label,
        "request": preset.request().model_dump(mode="json"),
        "fixture_file": path.name,
        "fetched_at": fetched_at or datetime.now(timezone.utc).replace(microsecond=0).isoformat(),
        "element_count": len(raw.get("elements", [])),
        "bytes": path.stat().st_size if path.is_file() else 0,
    }


def cmd_refresh_fixtures(args: argparse.Namespace) -> int:
    """Re-fetch the raw Overpass response behind each preset and rewrite the index."""
    selected = list(presets.PRESETS)
    if args.preset:
        unknown = [p for p in args.preset if p not in presets.PRESETS_BY_ID]
        if unknown:
            print(f"unknown preset(s): {', '.join(unknown)}", file=sys.stderr)
            return 2
        selected = [presets.PRESETS_BY_ID[p] for p in args.preset]

    previous: dict[str, dict[str, Any]] = {}
    if PRESETS_INDEX.is_file():
        try:
            for entry in json.loads(PRESETS_INDEX.read_text(encoding="utf-8"))["presets"]:
                previous[entry["preset_id"]] = entry
        except (ValueError, KeyError):
            previous = {}

    entries: dict[str, dict[str, Any]] = dict(previous)
    failures = 0
    for i, preset in enumerate(selected):
        request = preset.request()
        query = overpass.build_query(request)
        path = overpass.fixture_path(query)
        if args.if_missing and path.is_file():
            raw = overpass.read_fixture(path)
            remark = overpass.fatal_remark(raw)
            if remark is None:
                print(f"{preset.id}: cached ({path.name}), skipping")
                keep = previous.get(preset.id, {})
                fetched_at = (
                    keep.get("fetched_at") if keep.get("fixture_file") == path.name else None
                )
                entries[preset.id] = _index_entry(preset, raw, path, fetched_at)
                continue
            # a cached Overpass error body is not a fixture; fetch it again
            print(f"{preset.id}: cached {path.name} is a server error ({remark}), re-fetching")
        if i and not args.if_missing:
            time.sleep(REFRESH_PAUSE_S)
        print(f"{preset.id}: fetching {path.name} ...", flush=True)
        try:
            raw = overpass.fetch_and_cache(request)
        except overpass.OverpassError as exc:
            failures += 1
            print(f"{preset.id}: FAILED: {exc}", file=sys.stderr)
            continue
        entries[preset.id] = _index_entry(preset, raw, path)
        size_mb = path.stat().st_size / (1024 * 1024)
        print(f"{preset.id}: {entries[preset.id]['element_count']} elements, {size_mb:.1f} MB")

    ordered = [entries[p.id] for p in presets.PRESETS if p.id in entries]
    _write_presets_index(ordered)

    if len(ordered) == len(presets.PRESETS) and not args.keep_stale:
        current = {e["fixture_file"] for e in ordered}
        for stale in sorted(FIXTURES_DIR.glob("*.json")):
            if _SHA1_FIXTURE_RE.match(stale.name) and stale.name not in current:
                stale.unlink()
                print(f"removed stale fixture {stale.name}")

    return 1 if failures else 0


def _add_refresh_fixtures(sub: argparse._SubParsersAction) -> None:
    p = sub.add_parser(
        "refresh-fixtures",
        help="re-fetch the six preset Overpass fixtures (the only command that uses the network)",
    )
    p.add_argument("--preset", action="append", help="refresh only this preset id (repeatable)")
    p.add_argument(
        "--if-missing",
        action="store_true",
        help="only fetch presets that have no cached fixture yet",
    )
    p.add_argument(
        "--keep-stale",
        action="store_true",
        help="keep sha1-named fixtures that no preset points at any more",
    )
    p.set_defaults(handler=cmd_refresh_fixtures)



def _request_from_args(args: argparse.Namespace) -> SceneRequest:
    if args.preset:
        preset = presets.get_preset(args.preset)
        if preset is None:
            raise SystemExit(f"unknown preset: {args.preset}")
        return preset.request()
    if args.lat is None or args.lon is None:
        raise SystemExit("scene needs either --preset or --lat/--lon")
    return SceneRequest(
        lat=args.lat,
        lon=args.lon,
        radius_m=args.radius,
        rotation_deg=args.rotation,
        preset_id=None,
    )


def cmd_scene(args: argparse.Namespace) -> int:
    """Print the SceneGraph for a preset (or an ad-hoc location) as JSON."""
    request = _request_from_args(args)
    raw = overpass.load_raw(request, allow_network=not (args.offline or bool(request.preset_id)))
    scene = normalize.build_scene(raw, request)
    text = json.dumps(scene.model_dump(mode="json"), indent=None if args.compact else 2)
    if args.out:
        out = Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text + "\n", encoding="utf-8", newline="\n")
        stats = scene.stats
        print(
            f"wrote {out} - {stats.building_count} buildings, coverage={stats.coverage}, "
            f"height_tag_ratio={stats.height_tag_ratio:.3f}, roads={len(scene.roads)}, "
            f"water={len(scene.water)}, green={len(scene.green)}, trees={len(scene.trees)}"
        )
    else:
        print(text)
    return 0


def _add_scene(sub: argparse._SubParsersAction) -> None:
    p = sub.add_parser("scene", help="build a SceneGraph from a fixture (or Overpass) and print it")
    p.add_argument("--preset", help="preset id, e.g. chicago-loop (never uses the network)")
    p.add_argument("--lat", type=float)
    p.add_argument("--lon", type=float)
    p.add_argument("--radius", type=float, default=presets.PRESET_RADIUS_M, dest="radius")
    p.add_argument("--rotation", type=float, default=0.0, dest="rotation")
    p.add_argument("--out", help="write to this file instead of stdout")
    p.add_argument("--compact", action="store_true", help="one-line JSON")
    p.add_argument("--offline", action="store_true", help="fail instead of fetching on a cache miss")
    p.set_defaults(handler=cmd_scene)



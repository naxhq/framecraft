def _print_params_from_args(args: argparse.Namespace) -> "PrintParams":
    """``--params`` is a JSON object, or ``@file.json``; missing keys default."""
    from app.contracts import PrintParams

    raw = getattr(args, "params", None)
    if not raw:
        return PrintParams()
    if raw.startswith("@"):
        raw = Path(raw[1:]).read_text(encoding="utf-8")
    data = json.loads(raw)
    if not isinstance(data, dict):
        raise SystemExit("--params must be a JSON object")
    return PrintParams(**data)


def cmd_bake(args: argparse.Namespace) -> int:
    """Run the whole 04 pipeline synchronously and write every artifact."""
    from app import bake as bake_pipeline

    request = _request_from_args(args)
    params = _print_params_from_args(args)
    out = Path(args.out).resolve()
    if out.suffix.lower() not in (".3mf", ".stl"):
        raise SystemExit("--out must end in .3mf or .stl")

    started = time.perf_counter()
    raw = overpass.load_raw(request, allow_network=not (args.offline or bool(request.preset_id)))
    scene = normalize.build_scene(raw, request)
    print(
        f"scene: {scene.stats.building_count} buildings, coverage={scene.stats.coverage}, "
        f"roads={len(scene.roads)}, water={len(scene.water)}, green={len(scene.green)}, "
        f"trees={len(scene.trees)}"
    )

    def progress(stage: str, value: float) -> None:
        print(f"  [{value:4.0%}] {stage}", flush=True)

    try:
        result = bake_pipeline.run_pipeline(
            scene,
            request,
            params,
            job_id=out.stem,
            out_dir=out.parent,
            stem=out.stem,
            progress=progress,
        )
    except bake_pipeline.BakeError as exc:
        print(f"bake refused: {exc}", file=sys.stderr)
        return 2

    elapsed = time.perf_counter() - started
    stats = result.result.stats
    print()
    print(result.report.to_table())
    print()
    if stats is not None:
        print(
            f"triangles      {stats.triangles:,}\n"
            f"volume         {stats.volume_mm3:,.1f} mm^3\n"
            f"bounding box   {stats.bbox_mm[0]:.2f} x {stats.bbox_mm[1]:.2f} x "
            f"{stats.bbox_mm[2]:.2f} mm\n"
            f"filament       {stats.est_grams:.1f} g (ESTIMATE, 15% infill, 3 walls)\n"
            f"manifold       {'yes' if stats.is_manifold else 'no'}\n"
            f"min wall       {stats.min_wall_mm:.3f} mm (measured)"
        )
    for warning in result.result.warnings:
        print(f"warning: {warning}")
    for name, path in result.paths.items():
        print(f"{name:8s} {path}")
    print(f"bake time      {elapsed:.1f} s")
    if result.result.status != "done":
        print(f"FAILED: {result.result.error}", file=sys.stderr)
        if result.debug_dir is not None:
            print(f"intermediate solids: {result.debug_dir}", file=sys.stderr)
        return 1
    return 0


def _add_bake(sub: argparse._SubParsersAction) -> None:
    p = sub.add_parser("bake", help="run the printability pipeline and write .3mf/.stl/.json")
    p.add_argument("--preset", help="preset id, e.g. chicago-loop (never uses the network)")
    p.add_argument("--lat", type=float)
    p.add_argument("--lon", type=float)
    p.add_argument("--radius", type=float, default=presets.PRESET_RADIUS_M, dest="radius")
    p.add_argument("--rotation", type=float, default=0.0, dest="rotation")
    p.add_argument("--out", required=True, help="output path, e.g. ../../artifacts/chicago.3mf")
    p.add_argument("--params", help="PrintParams as JSON, or @file.json")
    p.add_argument("--offline", action="store_true", help="fail instead of fetching on a miss")
    p.set_defaults(handler=cmd_bake)


